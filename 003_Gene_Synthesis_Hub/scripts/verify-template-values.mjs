import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as XLSX from 'xlsx';
import {unzipSync,strFromU8} from 'fflate';
import {patchWorkbookValues} from '../src/ui/templateValues.js';
import {applyFullCalcOnLoad} from '../src/ui/xlsxPostProcess.js';
const bytes=fs.readFileSync(new URL('../python-app/Templates/Ligation_Template_v6.xlsx',import.meta.url));
const wb=XLSX.read(bytes,{type:'array'});
const formula=Object.entries(wb.Sheets.Layout).find(([ref,c])=>c.f && !['B2','T2'].includes(ref));
wb.Sheets.Layout.B2={t:'s',v:'TEST<&>"'};
wb.Sheets.Layout.T2={t:'n',v:1200};
wb.Sheets.Layout.B150={t:'s',v:'LATE-ROW'};
const dimension=XLSX.utils.decode_range(wb.Sheets.Layout['!ref']);dimension.e.r=150;wb.Sheets.Layout['!ref']=XLSX.utils.encode_range(dimension);
const out=new Uint8Array(patchWorkbookValues(bytes,wb));
const read=XLSX.read(out,{type:'array'});
assert.equal(read.Sheets.Layout.B2.v,'TEST<&>"');
assert.equal(read.Sheets.Layout.T2.v,1200);
assert.equal(read.Sheets.Layout.B150.v,'LATE-ROW');
assert(formula,'Original Layout formula missing');
assert.equal(read.Sheets.Layout[formula[0]]?.f,formula[1].f);
const before=unzipSync(bytes),after=unzipSync(out);
const changed=Object.keys(before).filter(key=>!Buffer.from(before[key]).equals(Buffer.from(after[key])));
assert.equal(changed.length,1,'Only the edited worksheet may change');
assert(changed[0].startsWith('xl/worksheets/'));
assert(strFromU8(after[changed[0]]).includes('s="'),'Cell styles must survive');
assert(strFromU8(unzipSync(applyFullCalcOnLoad(out.buffer))['xl/workbook.xml']).includes('fullCalcOnLoad="1"'),'ArrayBuffer post-processing must work, as in the real renderer');
console.log('Template value patch: exact strings/numbers, late rows, original formulas, styles, print settings and every untouched ZIP part preserved.');
