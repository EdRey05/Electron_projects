// Runs only in the isolated development guest, against the actual Electron app.
const {app,clipboard}=require('electron');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
process.env.NODE_ENV='production';
let stage='launcher';
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
app.on('browser-window-created',(_event,win)=>win.webContents.once('did-finish-load',async()=>{
 const js=code=>win.webContents.executeJavaScript(code);
 const until=async code=>{for(let n=0;n<150;n++){if(await js(code))return;await wait(150);}throw new Error('Timed out: '+code);};
 const click=async text=>{await js(`[...document.querySelectorAll('button')].find(b=>b.innerText.trim()===${JSON.stringify(text)}).click()`);await wait(100);};
 const field=async(selector,value)=>{await js(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error('Missing field');Object.getOwnPropertyDescriptor(e.tagName==='SELECT'?HTMLSelectElement.prototype:HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new Event('change',{bubbles:true}));})()`);await wait(80);};
 const open=async name=>{await js(`document.querySelector('[aria-label="Open ${name}"]').click()`);await wait(250);};
 const back=async()=>{await js(`[...document.querySelectorAll('button')].find(b=>b.innerText.trim().endsWith('Hub')).click()`);await wait(200);};
 const upload=async file=>{win.webContents.debugger.attach('1.3');try{const {root}=await win.webContents.debugger.sendCommand('DOM.getDocument');const {nodeId}=await win.webContents.debugger.sendCommand('DOM.querySelector',{nodeId:root.nodeId,selector:'input[type=file]'});await win.webContents.debugger.sendCommand('DOM.setFileInputFiles',{nodeId,files:[file]});}finally{win.webContents.debugger.detach();}};
 try{
  await until(`document.querySelectorAll('.gsh-tool-card').length===11`);assert(win.isMaximized());
  const root='C:/Export/discovery-ui';fs.mkdirSync(root+'/20261105',{recursive:true});
  fs.copyFileSync('C:/Export/synthetic-shipping.xlsx',root+'/20261105/shipping list for demo.xlsx');
  await js(`window.api.saveConfig({Shipping_List:${JSON.stringify(root)}},{})`);await click('Rescan');
  await until(`!![...document.querySelectorAll('button')].find(b=>b.innerText==='Rescan'&&!b.disabled)`);
  stage='label-discovery';await open('Label Generator');
  await until(`!![...document.querySelectorAll('button')].find(b=>b.innerText==='Autodiscovery'&&!b.disabled)`);
  await click('Autodiscovery');await until(`document.body.innerText.includes('20261105')`);
  await js(`document.querySelector('[role=dialog] input[type=checkbox]').click()`);await click('Proceed');
  await until(`document.body.innerText.includes('2 constructs loaded.')`);
  await field('[aria-label="Filter constructs"]','GeneTwo');
  await click('Check all shown');
  await js(`[...document.querySelectorAll('button')].find(b=>b.innerText.startsWith('Selected')).click()`);await wait(100);
  await click('Copy Selected');
  const copied=clipboard.readText();assert(copied.includes('GeneTwo'));assert(!copied.includes('GeneOne'));assert.equal(copied.split('\t').length,10);assert.equal(copied.split('\n').length,1);
  fs.writeFileSync('C:/Export/labels-refreshed-ui.png',(await win.webContents.capturePage()).toPNG());
  await click('Clear files');await upload('C:/Export/synthetic-shipping.xlsx');
  await until(`document.body.innerText.includes('2 constructs loaded.')`);
  assert(!(await js('document.body.innerText')).includes('already running'));
  stage='integra-controls';await back();await open('Integra Worklist');
  assert.equal(await js(`document.querySelectorAll('[aria-label="Row sort"]').length`),1);
  await field('[aria-label="Row sort"]','none');await click('Single entries');
  assert.equal(await js(`document.querySelectorAll('[aria-label="Row sort"]').length`),0);
  stage='upload-preview';await back();await open('QC File Prep');await field('[aria-label="QC workflow"]','upload');
  await until(`!!document.querySelector('[aria-label="In-House Progress workbook"]')`);
  const fixture=JSON.parse(fs.readFileSync('C:/Export/upload-ui-fixture.json','utf8'));
  await field('input[value$="QC_to_upload"]',fixture.outputFolder);
  // Set dependent folders before the workbook triggers the preview.
  await field('[aria-label="QC files received"]',fixture.paths.QC_Output_Folder);
  await field('[aria-label="Shipping list root"]',fixture.paths.Shipping_List);
  await field('[aria-label="In-House Progress workbook"]',fixture.workbook);
  await until(`document.querySelectorAll('input[aria-label^="Process "]').length===8`);
  assert.equal(await js(`document.querySelectorAll('input[aria-label^="Process "]:checked').length`),8);
  await js(`[...document.querySelectorAll('input[aria-label^="Process "]')].slice(1).forEach(e=>e.click())`);await wait(150);
  assert.equal(await js(`document.querySelectorAll('input[aria-label^="Process "]:checked').length`),1);
  fs.writeFileSync('C:/Export/upload-preview-ui.png',(await win.webContents.capturePage()).toPNG());
  await click('Process checked rows');await until(`document.body.innerText.includes('Complete.')`);
  assert.equal(await js(`document.querySelector('[aria-label="Upload execution progress"]').value`),1);
  const archived=path.join(fixture.paths.QC_Output_Folder,'..','3.6.6 QC files uploaded');
  assert(fs.existsSync(archived));assert(fs.existsSync(path.join(archived,'2026','BBI42-0 70001.zip')));
  assert(!fs.existsSync(path.join(fixture.paths.QC_Output_Folder,'BBI42-0 70001.zip')));
  assert(fs.existsSync(path.join(fixture.paths.QC_Output_Folder,'BBI42-1 70002.zip')),'Unchecked original was moved');
  stage='saved-organizer';await back();await open('Sequencing File Organizer');await click('Distribute References');await click('Load Last Session');
  await until(`document.body.innerText.includes('Loaded 1 Work Nos')`);
  stage='path-validation';await click('Organize Files');
  await field('#sfo-source-dir','C:/Export');
  await until(`getComputedStyle(document.querySelector('#sfo-source-dir')).borderTopColor==='rgb(46, 125, 66)'`);
  await field('#sfo-source-dir','C:/Export/does-not-exist-validated-test');
  await until(`document.querySelector('#sfo-source-dir').getAttribute('aria-invalid')==='true'`);
  assert.notEqual(await js(`getComputedStyle(document.querySelector('#sfo-source-dir')).borderTopColor`),'rgb(46, 125, 66)');
  await field('#sfo-source-dir','C:/Export');
  await until(`getComputedStyle(document.querySelector('#sfo-source-dir')).borderTopColor==='rgb(46, 125, 66)'`);
  fs.writeFileSync('C:/Export/validation-ui.png',(await win.webContents.capturePage()).toPNG());
  const result={status:'passed',maximized:true,labelAutodiscovery:true,filterAndSelectedClipboard:true,clipboardColumns:10,rapidClearAdd:true,bulkOnlySortSelector:true,uploadReviewed:8,uploadExecuted:1,uncheckedSourcePreserved:true,organizerSessionReload:true,greenValidRedInvalidRecovery:true};
  fs.writeFileSync('C:/Export/refresh-ui-result.json',JSON.stringify(result,null,2));app.exit(0);
 }catch(error){fs.writeFileSync('C:/Export/refresh-ui-error.txt',stage+'\n'+error.stack);fs.writeFileSync('C:/Export/refresh-ui-dom.txt',await js('document.body.innerText').catch(()=>''));app.exit(1);}
}));
require('../electron/main.js');
